#!/usr/bin/env python3
"""Stamp a "Checked <month>" line at the end of every guide section.

The date is the day the page was last revised for a product change
(site_blocks.page_date, the same source as the hero's SAG-STAMP), unless
site_data.SECTION_CHECKS names a later date for that one section. The line
links to the change log. Markup sits between SAG-CHECKED markers as the
last child of each `.accordion[id]`, so a rerun replaces it.

    python3 build-stamps.py

Never hand-edit the injected block: the next run overwrites it.
"""

import re
import sys
from pathlib import Path

from site_blocks import month_label, page_date
from site_data import CHANGELOG_PAGE, GUIDES, SECTION_CHECKS

ROOT = Path(__file__).parent
START = "<!-- SAG-CHECKED:START — generated by build-stamps.py, do not hand-edit -->"
END = "<!-- /SAG-CHECKED:END -->"
MARKER_RE = re.compile(r"\s*" + re.escape(START) + r".*?" + re.escape(END), re.S)
SECTION_RE = re.compile(r'<div class="accordion" id="([^"]+)">')
DIV_RE = re.compile(r"<div\b|</div>")
INDENT = "  "


def stamp_html(iso, label):
    markup = (
        f'<p class="sag-checked"><span>Checked <time datetime="{iso}">{label}</time></span>'
        f'<a href="{CHANGELOG_PAGE}">What changed &rarr;</a></p>'
    )
    return markup


def section_date(page, section_id):
    """The later of the page's revision date and any per-section check."""
    override = SECTION_CHECKS.get((page, section_id), "")
    iso = max(page_date(page), override)
    return iso


def closing_div(source, open_start):
    """Index of the `</div>` that closes the div opened at open_start."""
    depth = 0
    position = -1
    for match in DIV_RE.finditer(source, open_start):
        depth += 1 if match.group(0) == "<div" else -1
        if depth == 0:
            position = match.start()
            break
    if position < 0:
        raise ValueError("unbalanced <div> after offset %d" % open_start)
    return position


def stamp_page(page, source):
    """Return the page with a fresh stamp in every section."""
    cleaned = MARKER_RE.sub("", source)
    pieces = []
    cursor = 0
    for section in SECTION_RE.finditer(cleaned):
        close = closing_div(cleaned, section.start())
        iso = section_date(page, section.group(1))
        block = f"\n{INDENT}{START}\n{INDENT}{stamp_html(iso, month_label(iso))}\n{INDENT}{END}\n{INDENT}"
        pieces.append(cleaned[cursor:close].rstrip(" "))
        pieces.append(block)
        cursor = close
    pieces.append(cleaned[cursor:])
    result = "".join(pieces)
    return result


def build_one(guide):
    path = ROOT / guide.file
    source = path.read_text(encoding="utf-8")
    updated = stamp_page(guide.file, source)
    changed = updated != source
    if changed:
        path.write_text(updated, encoding="utf-8")
    return changed


def main():
    changed = 0
    for guide in GUIDES:
        if build_one(guide):
            changed += 1
            print(f"  {guide.file}")
    print(f"{changed} of {len(GUIDES)} guides updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
