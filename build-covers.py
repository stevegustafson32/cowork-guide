#!/usr/bin/env python3
"""Stamp the paper book cover into every guide hero.

Each guide's hero gets its cover as the last child of `<div class="hero">`,
between SAG-COVER markers so a rerun replaces it. The title, subtitle and
volume number come from site_data.COVERS and GUIDES; the date comes from the
shared SAG-STAMP marker so check-stale.py keeps it current. cover.css is
linked after nav.css on any guide that does not have it yet.

    python3 build-covers.py

Never hand-edit the injected block: the next run overwrites it.
"""

import re
import sys
from pathlib import Path

from site_data import COVERS, GUIDES

ROOT = Path(__file__).parent
START = "<!-- SAG-COVER:START — generated by build-covers.py, do not hand-edit -->"
END = "<!-- /SAG-COVER:END -->"
AUTHOR = "Steve Gustafson"
SITE = "stevesaiguide.com"
STAMP_RE = re.compile(r"<!-- SAG-STAMP(?::upper)? -->(.*?)<!-- /SAG-STAMP -->")
HERO_OPEN_RE = re.compile(r'<div class="hero">')
HERO_CLOSE_RE = re.compile(r"\n</div>\n", re.S)
MARKER_RE = re.compile(r"\n?" + re.escape(START) + r".*?" + re.escape(END), re.S)
NAV_LINK_RE = re.compile(r'<link rel="stylesheet" href="nav\.css[^"]*">')
COVER_LINK = '<link rel="stylesheet" href="cover.css">'


def cover_html(volume, title_html, subtitle, stamp):
    """The cover block for one guide. Shared with build-og.py."""
    markup = f'''<div class="guide-cover" aria-hidden="true">
  <div class="cover-top">
    <span>Vol. {volume:02d} · {stamp}</span>
    <span class="cover-mark">S</span>
  </div>
  <div class="cover-mid">
    <div class="cover-title">{title_html}</div>
    <p class="cover-sub">{subtitle}</p>
  </div>
  <div class="cover-bottom">
    <span>{AUTHOR}</span>
    <em>{SITE}</em>
  </div>
</div>'''
    return markup


def month_stamp(source):
    """The page's own 'Month YYYY' stamp, title-cased, or a fallback."""
    found = STAMP_RE.search(source)
    stamp = found.group(1).strip().title() if found else "2026"
    return stamp


def inject(source, block):
    """Place the block as the hero's last child, replacing any older one."""
    cleaned = MARKER_RE.sub("", source)
    hero = HERO_OPEN_RE.search(cleaned)
    if not hero:
        raise ValueError("no <div class=\"hero\"> found")
    close = HERO_CLOSE_RE.search(cleaned, hero.end())
    wrapped = f"\n{START}\n{block}\n{END}"
    result = cleaned[:close.start()] + wrapped + cleaned[close.start():]
    return result


def link_stylesheet(source):
    """Add cover.css right after nav.css, once."""
    result = source
    if 'href="cover.css' not in source:
        result = NAV_LINK_RE.sub(lambda m: m.group(0) + "\n  " + COVER_LINK, source, count=1)
    return result


def build_one(volume, guide):
    path = ROOT / guide.file
    source = path.read_text(encoding="utf-8")
    cover = COVERS[guide.file]
    block = cover_html(volume, cover.title_html, cover.subtitle, month_stamp(source))
    updated = link_stylesheet(inject(source, block))
    changed = updated != source
    if changed:
        path.write_text(updated, encoding="utf-8")
    return changed


def main():
    changed = 0
    for volume, guide in enumerate(GUIDES, 1):
        if build_one(volume, guide):
            changed += 1
            print(f"  {guide.file}")
    print(f"{changed} of {len(GUIDES)} guides updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
